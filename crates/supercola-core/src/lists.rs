pub fn buscar(grupos: &[Grupo], texto: &str) -> Vec<&'static str> {
    let q = Query::new(texto);
    let mut saida: Vec<&'static str> = Vec::new();
    for g in grupos {
        for item in g.itens {
            if q.matches(item) && !saida.contains(item) {
                saida.push(item);
            }
        }
    }
    saida
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn grupos_preenchidos() {
        assert!(KAOMOJI.iter().chain(SIMBOLOS).all(|g| !g.itens.is_empty()));
    }

    #[test]
    fn busca_sem_repetir() {
        let r = buscar(SIMBOLOS, "");
        let mut unicos = r.clone();
        unicos.sort_unstable();
        unicos.dedup();
        assert_eq!(unicos.len(), r.len());
        assert!(!buscar(KAOMOJI, "ツ").is_empty());
    }
}
